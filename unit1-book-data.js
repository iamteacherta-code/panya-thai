/* ============================================================
   ตัวจัดหน้าเนื้อเรื่อง
   แบ่ง "ตอน" ลงหน้ากระดาษโดยประมาณจากจำนวนบรรทัดที่แต่ละย่อหน้ากินจริง
   ไม่ใช่แบ่งครึ่งจำนวนตอน มิฉะนั้นบทที่ย่อหน้ายาวจะล้นหน้า

     budget   = จำนวน "บรรทัด" ที่หน้าหนึ่งรับได้
     perLine  = จำนวนตัวอักษรโดยประมาณต่อหนึ่งบรรทัด
   คืนค่าเป็น array ของ array ของตอน (หนึ่งช่อง = หนึ่งหน้า)
   ============================================================ */
function paginateStory(chapter, budget, perLine) {
  budget = budget || 24;
  perLine = perLine || 66;
  const clean = (s) => s.replace(/[*~]/g, "");
  const cost = (ep) =>
    1.2 + ep.paras.reduce((n, p) => n + Math.max(1, Math.ceil(clean(p).length / perLine)) + 0.15, 0);

  const pack = (b) => {
    const pages = [];
    let page = [], used = 0;
    chapter.story.forEach((ep) => {
      const c = cost(ep);
      if (page.length && used + c > b) { pages.push(page); page = []; used = 0; }
      page.push(ep);
      used += c;
    });
    if (page.length) pages.push(page);
    return pages;
  };

  const full = pack(budget);
  const n = full.length;
  if (n < 2) return full;

  // ใช้จำนวนหน้าเท่าเดิม แต่เกลี่ยเนื้อหาให้แต่ละหน้าใกล้เคียงกัน
  // ด้วยการหาค่า budget ที่เล็กที่สุดที่ยังได้จำนวนหน้าเท่ากับ n
  const total = chapter.story.reduce((s, ep) => s + cost(ep), 0);
  for (let b = total / n; b < budget; b += 0.25) {
    const p = pack(b);
    if (p.length === n) return p;
  }
  return full;
}
BOOK.paginateStory = paginateStory;

